const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const puppeteer = require(process.env.PUPPETEER_MODULE || path.join(process.env.APPDATA, 'npm/node_modules/puppeteer'));
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'build/verification');
fs.mkdirSync(output, { recursive: true });
const mapDir = path.join(root, 'map-assets');
const localMapCount = fs.existsSync(mapDir) ? fs.readdirSync(mapDir).filter(file => file.endsWith('.webp')).length : 0;
assert.ok(localMapCount === 0 || localMapCount === 53, `Expected 0 or 53 local maps, got ${localMapCount}`);
const hasOfflineMaps = localMapCount === 53;
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('sqd-fire-control-v1')));
  try {
    await page.setOfflineMode(hasOfflineMaps);
    await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    const maps = await page.evaluate(() => MortarCalc.maps.map(map => map.id));
    assert.equal(maps.length, 53);
    if (hasOfflineMaps) {
      await page.waitForFunction(() => document.querySelector('#mapRaster').naturalWidth > 0);
      for (const id of maps) {
        await page.select('#mapSelect', id);
        await page.waitForFunction(id => document.querySelector('#mapRaster').src.includes('/' + id + '.webp') && document.querySelector('#mapRaster').complete && document.querySelector('#mapRaster').naturalWidth > 0, {}, id);
      }
      console.log('PASS all 53 map selections load while offline');
      await page.select('#mapSelect', 'al-basrah');
    } else {
      console.log('PASS all 53 map definitions; local image assets are intentionally omitted');
    }
    for (const width of [360, 390, 768]) {
      await page.setViewport({ width, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
      await pause(100);
      const metrics = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth, stage: document.querySelector('#mapStage').getBoundingClientRect().height, footer: document.querySelector('.map-footer').getBoundingClientRect().bottom, inlineBottom: document.querySelector('.mobile-solutions').getBoundingClientRect().bottom, bottom: innerHeight }));
      assert.ok(metrics.scroll <= width + 1, JSON.stringify(metrics));
      assert.ok(metrics.stage > 200, JSON.stringify(metrics));
      assert.ok(metrics.footer <= metrics.bottom, JSON.stringify(metrics));
      assert.ok(metrics.inlineBottom <= metrics.bottom, JSON.stringify(metrics));
    }
    await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    await pause(100);
    await page.click('#targetModeBtn');
    let box = await page.$eval('#mapStage', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; });
    const x = box.x + box.width * 0.24, y = box.y + box.height * 0.26;
    let before = await state();
    await page.touchscreen.tap(x, y);
    assert.equal((await state()).targets.length, before.targets.length + 1, 'tap adds exactly one target');
    assert.equal(await page.$eval('body', el => el.dataset.mobilePanel), 'map', 'solutions stay on the map panel');
    assert.equal(await page.$('[data-panel="solutions"]'), null, 'no separate mobile target-list tab');
    const newTargetId = (await state()).selectedTargetId;
    let mobileRow = await page.$('.mobile-solution-row.selected');
    assert.ok(mobileRow, 'new target is selected in the inline results');
    const mobileText = await mobileRow.evaluate(el => el.innerText);
    assert.match(mobileText, /方位/);
    assert.match(mobileText, /mil/);
    assert.match(mobileText, /m|km/);
    await page.evaluate(() => { window.Platform.copyText = value => { window.__copiedCall = value; return Promise.resolve(); }; });
    await page.click('.mobile-solution-row[data-target-id="' + newTargetId + '"] button[aria-label^="复制"]');
    assert.match(await page.evaluate(() => window.__copiedCall), new RegExp(newTargetId + '.*mil'));
    await page.$eval('.mobile-solution-row[data-target-id="' + newTargetId + '"] .target-elevation', el => { el.value = '45'; el.dispatchEvent(new Event('change', { bubbles: true })); });
    assert.equal((await state()).targets.find(target => target.id === newTargetId).elevation, 45, 'inline target height updates');
    await page.click('.mobile-solution-row[data-target-id="' + newTargetId + '"] button[aria-label^="删除"]');
    assert.equal((await state()).targets.some(target => target.id === newTargetId), false, 'inline target delete works');
    box = await page.$eval('#mapStage', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; });
    const panX = box.x + box.width * 0.35, panY = box.y + box.height * 0.35;
    const cdp = await page.createCDPSession();
    const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points.map(([id, x, y]) => ({ id, x, y, radiusX: 3, radiusY: 3 })) });
    before = await state();
    await touch('touchStart', [[0, panX + 30, panY + 30]]);
    await touch('touchMove', [[0, panX + 70, panY + 50]]);
    await touch('touchEnd', []);
    let after = await state();
    assert.equal(after.targets.length, before.targets.length, 'pan does not add a target');
    assert.ok(after.panX > before.panX + 30, 'one finger pans');
    const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
    before = await state();
    await touch('touchStart', [[0, cx - 35, cy], [1, cx + 35, cy]]);
    await touch('touchMove', [[0, cx - 65, cy], [1, cx + 65, cy]]);
    await touch('touchEnd', []);
    after = await state();
    assert.ok(after.zoom > before.zoom * 1.5, 'two fingers zoom');
    assert.equal(after.targets.length, before.targets.length, 'pinch does not add a target');
    const glyphs = await page.$$eval('.marker-glyph', nodes => nodes.map(el => { const r = el.getBoundingClientRect(); return [r.width, r.height]; }));
    glyphs.forEach(size => assert.deepEqual(size, [5, 5]));
    await page.click('#fitBtn');
    const marker = await page.$eval('.marker.target', el => { const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2, id: el.dataset.id }; });
    before = await state();
    await touch('touchStart', [[0, marker.x, marker.y]]);
    await touch('touchMove', [[0, marker.x + 25, marker.y + 10]]);
    await touch('touchEnd', []);
    after = await state();
    assert.ok(after.targets.find(t => t.id === marker.id).x > before.targets.find(t => t.id === marker.id).x, 'marker drag changes coordinate');
    const centers = await page.evaluate(id => {
      const a = document.querySelector('.marker.target[data-id="' + id + '"] .marker-glyph').getBoundingClientRect();
      const b = document.querySelector('.target-rings[data-target-id="' + id + '"]').getBoundingClientRect();
      return [a.x + a.width / 2 - b.x, a.y + a.height / 2 - b.y];
    }, marker.id);
    centers.forEach(delta => assert.ok(Math.abs(delta) < 0.1, 'damage ring stays centered'));
    await page.screenshot({ path: path.join(output, 'android-mobile-map.png') });
    await page.click('[data-panel="setup"]');
    await page.select('#weaponSelect', 'mortar-table-squ');
    await page.click('[data-panel="map"]');
    assert.ok(await page.$eval('#mobileSolutionsList', el => el.getBoundingClientRect().height > 0));
    await page.screenshot({ path: path.join(output, 'android-mobile-targets.png') });
    const saved = await state();
    await page.reload();
    assert.deepEqual((await state()).targets, saved.targets, 'targets persist after reload');
    const plan = { ...saved, version: 1, layer: 'AAS v1', targets: Array.from({ length: 25 }, (_, i) => ({ id: String.fromCharCode(65 + i), x: .9, y: .9, elevation: 0 })) };
    const planPath = path.join(output, 'roundtrip-plan.json');
    fs.writeFileSync(planPath, JSON.stringify(plan));
    const input = await page.$('#planFileInput');
    await input.uploadFile(planPath);
    await page.waitForFunction(() => document.querySelector('#solutionCount').textContent === '25');
    assert.equal((await state()).layer, 'basemap', 'legacy layer imports into offline basemap');
    if (hasOfflineMaps) await page.waitForFunction(() => document.querySelector('#mapRaster').naturalWidth > 0);
    await page.click('#targetModeBtn');
    const tapBox = await page.$eval('#mapStage', el => { const r = el.getBoundingClientRect(); return { x: r.x + r.width * .1, y: r.y + r.height * .1 }; });
    await page.touchscreen.tap(tapBox.x, tapBox.y);
    assert.equal((await state()).targets.length, 26, '26th target can be added');
    const lastRow = await page.$('.mobile-solution-row[data-target-id="Z"]');
    assert.ok(lastRow, 'new last target is in inline results');
    const scrolledRow = await lastRow.evaluate(el => { const list = el.parentElement; const row = el.getBoundingClientRect(); const bounds = list.getBoundingClientRect(); return list.scrollTop > 0 && row.bottom <= bounds.bottom + 1 && row.top >= bounds.top - 1; });
    assert.ok(scrolledRow, 'new target is automatically revealed in the scrollable list');
    page.once('dialog', dialog => dialog.accept());
    const fullMapBox = await page.$eval('#mapStage', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; });
    await page.touchscreen.tap(fullMapBox.x + fullMapBox.width * .12, fullMapBox.y + fullMapBox.height * .12);
    assert.equal((await state()).targets.length, 26, 'target limit enforced');
    let exported;
    await page.exposeFunction('captureExport', content => { exported = JSON.parse(content); });
    await page.evaluate(() => { window.Platform.savePlan = content => window.captureExport(content); });
    await page.click('#exportBtn');
    assert.equal(exported.targets.length, 26, 'export includes all targets');
    assert.equal(exported.mapId, plan.mapId);
    console.log('PASS plan import/export, legacy layer compatibility and 26-target limit');
    console.log('PASS mobile layouts, tap, pan, pinch, 5px glyphs, marker drag/ring center, persistence');
    await page.setViewport({ width: 1440, height: 960, deviceScaleFactor: 1, isMobile: false, hasTouch: false });
    await pause(100);
    await page.click('#fitBtn');
    box = await page.$eval('#mapStage', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; });
    await page.mouse.move(box.x + box.width * 0.4, box.y + box.height * 0.4);
    await page.mouse.wheel({ deltaY: -400 });
    await pause(100);
    assert.ok((await state()).zoom > 1, 'desktop wheel zooms');
    await page.screenshot({ path: path.join(output, 'windows-desktop.png') });
    assert.deepEqual(errors, [], 'no JavaScript runtime errors');
    console.log('PASS desktop wheel zoom and no runtime errors');
    fs.writeFileSync(path.join(output, 'ui-result.json'), JSON.stringify({ passed: true, maps: maps.length, viewportWidths: [360, 390, 768, 1440], errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
